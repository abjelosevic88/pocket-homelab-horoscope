//go:build ignore

// Command gen truncates the VSOP87B series (heliocentric spherical, J2000
// ecliptic) into internal/astro/vsop87_data.go.
//
// Download the files from https://ftp.imcce.fr/pub/ephem/planets/vsop87/
// (VSOP87B.mer … VSOP87B.nep) into a directory, then from internal/astro:
//
//	go run gen/main.go -dir /tmp/vsop87 -out vsop87_data.go
//
// A term A·cos(B + C·t)·tⁿ (t in Julian millennia from J2000) is kept when
// A·0.3ⁿ ≥ threshold, i.e. when it can matter between 1700 and 2300. Terms are
// written largest first so the evaluator can stop early for coarse work.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type term struct{ a, b, c float64 }

func main() {
	dir := flag.String("dir", "/tmp/vsop87", "directory with VSOP87B.* files")
	out := flag.String("out", "vsop87_data.go", "output file")
	thr := flag.Float64("threshold", 1e-7, "amplitude threshold (radians / AU)")
	flag.Parse()

	planets := []struct{ ext, name string }{
		{"mer", "mercury"}, {"ven", "venus"}, {"ear", "earth"}, {"mar", "mars"},
		{"jup", "jupiter"}, {"sat", "saturn"}, {"ura", "uranus"}, {"nep", "neptune"},
	}
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go from VSOP87B (Bretagnon & Francou 1988); DO NOT EDIT.\n\n")
	b.WriteString("package astro\n\n")
	fmt.Fprintf(&b, "// Truncation threshold: %g (A·0.3ⁿ).\n", *thr)
	b.WriteString("var vsopData = map[string]vsopPlanet{\n")
	total := 0
	for _, p := range planets {
		series, err := parse(filepath.Join(*dir, "VSOP87B."+p.ext))
		if err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&b, "\t%q: {\n", p.name)
		for v := 0; v < 3; v++ {
			b.WriteString("\t\t{\n")
			for n := 0; n < len(series[v]); n++ {
				lim := *thr
				for i := 0; i < n; i++ {
					lim /= 0.3
				}
				b.WriteString("\t\t\t{")
				terms := series[v][n]
				sort.SliceStable(terms, func(i, j int) bool { return terms[i].a > terms[j].a })
				for _, t := range terms {
					if t.a < lim {
						continue
					}
					total++
					fmt.Fprintf(&b, "{%s, %s, %s}, ", g(t.a), g(t.b), g(t.c))
				}
				b.WriteString("},\n")
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s: %d terms", *out, total)
}

func g(f float64) string { return strconv.FormatFloat(f, 'g', 12, 64) }

// parse returns series[variable][power] terms.
func parse(path string) ([3][][]term, error) {
	var s [3][][]term
	f, err := os.Open(path)
	if err != nil {
		return s, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	v, n := -1, -1
	for sc.Scan() {
		line := sc.Text()
		if strings.Contains(line, "VSOP87") {
			i := strings.Index(line, "VARIABLE")
			v, _ = strconv.Atoi(strings.TrimSpace(line[i+8 : i+11]))
			v--
			j := strings.Index(line, "*T**")
			n, _ = strconv.Atoi(strings.TrimSpace(line[j+4 : j+6]))
			for len(s[v]) <= n {
				s[v] = append(s[v], nil)
			}
			continue
		}
		fs := strings.Fields(line)
		if len(fs) < 3 || v < 0 {
			continue
		}
		a, _ := strconv.ParseFloat(fs[len(fs)-3], 64)
		bb, _ := strconv.ParseFloat(fs[len(fs)-2], 64)
		c, _ := strconv.ParseFloat(fs[len(fs)-1], 64)
		s[v][n] = append(s[v][n], term{a, bb, c})
	}
	return s, sc.Err()
}
